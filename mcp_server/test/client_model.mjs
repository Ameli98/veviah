// Q13a / Q13b (2026-11-13): the MCP server uses the app's model (companion /model/info) and reports its client's name.
import { spawn } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const PORT = '8798', DATA = await fs.mkdtemp(path.join(os.tmpdir(), 'hsin-cm-'));
const D = path.join(HERE, '../../vrm_player/public/models/AvatarSample_D.vrm');
const comp = spawn(process.execPath, [path.join(HERE, '../companion.mjs')], { env: { ...process.env, HSIN_COMPANION_PORT: PORT, HSIN_VRM_MODEL: D, HSIN_DATA: DATA }, stdio: ['ignore', 'ignore', 'pipe'] });
await new Promise((r) => comp.stderr.on('data', (d) => { if (String(d).includes('open http')) r(); }));
let fail = 0; const ok = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) fail++; };
const client = new Client({ name: 'test-client', version: '9.9' });
let serverLog = '';
const t = new StdioClientTransport({ command: process.execPath, args: [path.join(HERE, '../server.mjs')], env: { ...process.env, HSIN_COMPANION_PORT: PORT, HSIN_DATA: DATA }, stderr: 'pipe' });
t.stderr.on('data', (d) => { serverLog += d; });
await client.connect(t);
await new Promise((r) => setTimeout(r, 800));
const clients = await (await fetch(`http://127.0.0.1:${PORT}/clients`)).json();
ok(clients['test-client']?.version === '9.9', 'the app knows the AI program: ' + JSON.stringify(clients));
const kf = [{ t: 0 }, { t: 0.8, right_arm: { hand: 'head out beside' } }, { t: 1.6 }];
const r = await client.callTool({ name: 'perform', arguments: { say: 'hi', emotion: 'happy', posture: 'stand', keyframes: kf } });
ok(/AvatarSample_D/.test(serverLog), "the server solved on the app's model (AvatarSample_D), not its own default: " + (serverLog.match(/motion \S+: [^\n]*/) ?? [''])[0]);
await client.close();
await fetch(`http://127.0.0.1:${PORT}/quit`, { method: 'POST' }).catch(() => {});
await fs.rm(DATA, { recursive: true, force: true });
console.log(fail ? `${fail} failed` : 'all ok'); process.exit(fail ? 1 : 0);
